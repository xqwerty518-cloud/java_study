/**
 * 클래스 C에는 int 값을 받은 생성자가 1개 정의돼 있다 기본 생성자는 아니더라도 생성자가 있으므로 컴파일러는
 * 기본 생성자를 추가해 주지 않을 것이다. 이제 클래스 D를 정의하고 
 * 클래스 C를 상속하면 내부에 아무런 코드를 작성하지도 않았는데 상속받자마자 오류가 발생한다.
 * 클래스 D 안에는 생성자가 없으므로 컴파일러가 기본 생성자를 자동으로 삽입해 줄것이다. 
 * 또한 모든 생성자의 첫 줄에는 this() 또는 super()가 있어야 하므로 
 * 컴파일러는 추가로 기본 생성자의 첫 줄에 super() 메서드를 추가한다. 
 * 앞에서 설명한 것처럼 super()는 부모의 기본 생성자 즉 C() 를 호출하라는 의미이다. 
 * 하지만 클래스 C는 기본생성자를 포함하고 있지 않으므로 오류가 발생하는 것이다. 
 * 이를 해결하기 위해서는 super(3)과 같이 정수를 입력받는 부모의 생성자를 명시적으로 호출해야 한다. 
 */

class D extends C {
	D(){
		super(3);
	}
}

